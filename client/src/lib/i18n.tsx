export type TranslationKey = keyof typeof en
const DICTS: Record<LangCode, Record<TranslationKey, string>> = { en, th }

interface I18nContextValue {
  lang: LangCode
  setLang: (l: LangCode) => void
  t: (k: TranslationKey | string) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

function readInitialLang(): LangCode {
  try {
    const saved = localStorage.getItem('tlr_lang')
    if (saved === 'en' || saved === 'th') return saved
  } catch { /* ignore */ }
  return 'en'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>(readInitialLang)

  useEffect(() => {
    document.documentElement.lang = lang
  }, [lang])

  const setLang = (next: LangCode) => {
    setLangState(next)
    try {
      localStorage.setItem('tlr_lang', next)
    } catch { /* ignore */ }
  }

  const t = (k: TranslationKey | string): string => {
    const dict = DICTS[lang] || DICTS.en
    return (dict as Record<string, string>)[k] ?? (DICTS.en as Record<string, string>)[k] ?? String(k)
  }

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider')
  return ctx
}
